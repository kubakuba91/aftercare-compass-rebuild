/** Cities, county seats, and nicknames for the states that have resource pages. */

export type SearchPlace = {
  state: string;
  /** City name when the match is a city. */
  city?: string;
  /** County name when the match is a county or a county seat. */
  county?: string;
  /** Lowercase phrases that should resolve to this place. Longer phrases win. */
  names: string[];
};

