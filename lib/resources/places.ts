function norm(value: string) {
  return value
    .toLowerCase()
    .replace(/[’']/g, "")
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

function statePlace(code: string, name: string, extra: string[] = []): SearchPlace {
  return { state: code, names: [norm(name), norm(code), ...extra.map(norm)] };
}

function city(state: string, name: string, county?: string, extra: string[] = []): SearchPlace {
  const names = [name, ...extra];
  if (county) names.push(`${county} county`);
  return {
    state,
    city: name,
    county: county ? `${county} County` : undefined,
    names: names.map(norm)
  };
}

function county(state: string, name: string, seat?: string): SearchPlace {
  const names = [name, `${name} county`];
  if (seat) names.push(seat);
  return {
    state,
    city: seat,
    county: `${name} County`,
    names: names.map(norm)
  };
}

